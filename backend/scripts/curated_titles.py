"""Curated, hand-written title catalog content.

Themes: sci-fi (Star Trek, Star Wars, Dune), fantasy (LOTR, Witcher,
Fable, Zelda, Skyrim, Dark Souls, Tolkien), supernatural (Buffy,
Supernatural, X-Files), gaming (varied), music (paraphrased lyric
references / genres), books, film/TV, internet/meme culture, mythology
(non-religious), and assorted milestones.

Rules (audit before adding entries):
- No politics. No religion. No history.
- No belittling. No promotion of unhealthy living.
- Avoid verbatim trademarked phrases or full song lyrics. Use evocative
  paraphrases.
- Each entry uses one of the implemented condition kinds in
  `app/services/title_service.py`.
"""

from __future__ import annotations

import re
from typing import Any

# (name, rarity, condition_kind, threshold-or-params, description, category)
# `params` is an int (threshold) for scalar kinds or a dict for
# `exercise_type_minutes`.
Entry = tuple[str, str, str, Any, str, str]


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def _entries_to_dicts(
    entries: list[Entry], theme: str
) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    seen: set[str] = set()
    for idx, (name, rarity, kind, params, desc, category) in enumerate(entries):
        base_slug = f"curated_{theme}_{_slug(name)}"
        slug = base_slug
        # If collisions ever happen (similar names across themes), suffix idx.
        if slug in seen:
            slug = f"{base_slug}_{idx}"
        seen.add(slug)
        condition_params: dict[str, Any] = (
            params if isinstance(params, dict) else {"threshold": int(params)}
        )
        rows.append(
            {
                "slug": slug,
                "name": name,
                "description": desc,
                "category": category,
                "rarity": rarity,
                "condition_kind": kind,
                "condition_params": condition_params,
                "opt_out_group": None,
                "is_secret": False,
                "sort_order": idx,
            }
        )
    return rows


